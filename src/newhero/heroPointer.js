/**
 * ตำแหน่งเมาส์สำหรับ parallax ของฉาก — **อ่านจากหน้าต่าง ไม่ใช่จากแคนวาส**
 *
 * r3f มี `state.pointer` ให้อยู่แล้ว แต่มันอัปเดตจากอีเวนต์ที่ *ตกบนแคนวาส* เท่านั้น
 * /new-hero วางแคนวาสเต็มจอ จึงได้ parallax ทั่วจอ ส่วน /2026-final วางแคนวาสไว้ในกรอบ
 * การ์ดที่มีชั้นอื่นทับอยู่ (บล็อกตัวหนังสือของจอแรก ราวจุดด้านซ้าย แถบบนสุด) พื้นที่ที่
 * เมาส์ "ถึงแคนวาสจริง" จึงเป็นแค่บางส่วนของจอ — เลื่อนเมาส์เหนือหัวเรื่องแล้วกล้องนิ่งสนิท
 *
 * ตัวนี้ฟังที่ `window` ชั้นเดียวทั้งหน้า ค่าจึงเป็น "เมาส์อยู่ไหนบนจอ" จริง ๆ ไม่ขึ้นกับว่า
 * อะไรทับแคนวาสอยู่ และเป็นค่าเดียวกันทั้งสองหน้า — ฉากเดียวกันก็ต้องได้ parallax เท่ากัน
 *
 * ช่วงค่าเท่ากับ `state.pointer` ของ r3f เป๊ะ (−1..1 โดย y ชี้ขึ้น) ของที่เคยคูณค่านั้นอยู่
 * จึงย้ายมาใช้ตัวนี้ได้โดยไม่ต้องแก้สเกลของตัวเอง
 *
 * เป็นกล่องเปล่า ไม่ใช่ state ของ React: ค่าเปลี่ยนทุกครั้งที่เมาส์ขยับ ซึ่งถี่กว่าเฟรม
 */
export const heroPointer = { x: 0, y: 0 }

/** ใครติดตั้งไว้กี่เจ้า — ตัวฟังมีตัวเดียวเสมอ ถอนเมื่อคนสุดท้ายเลิกใช้ */
let users = 0
let detach = null

/**
 * ติดตั้งตัวฟัง (เรียกได้หลายที่ ตัวฟังยังมีตัวเดียว) — คืนฟังก์ชันถอน
 *
 * `pointermove` ครอบทั้งเมาส์และปากกา ส่วนนิ้วบนจอสัมผัสไม่ต้องขับ parallax: มันไม่มี
 * "ตำแหน่งพัก" ค่าจะค้างที่จุดที่แตะครั้งสุดท้าย — กล้องจึงเอียงค้างอยู่อย่างนั้น
 */
export function holdHeroPointer() {
  users += 1
  if (!detach && typeof window !== 'undefined') {
    const on = (e) => {
      if (e.pointerType === 'touch') return
      const w = window.innerWidth || 1
      const h = window.innerHeight || 1
      heroPointer.x = (e.clientX / w) * 2 - 1
      heroPointer.y = -((e.clientY / h) * 2 - 1)
    }
    window.addEventListener('pointermove', on, { passive: true })
    detach = () => window.removeEventListener('pointermove', on)
  }
  return () => {
    users -= 1
    if (users <= 0 && detach) {
      detach()
      detach = null
      users = 0
    }
  }
}
