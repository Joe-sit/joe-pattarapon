import { useSyncExternalStore } from 'react'

/**
 * ความคืบหน้าของ "ช่วงไหล" ท้าย hero — 0 = จบอินโทรพอดี, 1 = ริบบิ้นถึงมุมขวาสุด
 *
 * ไม่ใช่ React state: ค่านี้เปลี่ยนทุกเฟรมที่ผู้ใช้เลื่อนจอ ถ้าเก็บใน state ทั้งหน้าจะ
 * re-render ตามการเลื่อน (ฉาก 3D ทั้งฉากถูก reconcile ใหม่) — ตัวเลขเปล่า ๆ ในโมดูล
 * แล้วให้ useFrame อ่านเอา คือทางที่ r3f ตั้งใจให้ใช้กับค่าที่มาจากนอกฉาก
 *
 * หน้าเป็นคนเขียน (ดู Portfolio2026FinalPage) ฉากเป็นคนอ่าน
 */
const state = { p: 0 }

export function setCruise(v) {
  state.p = v < 0 ? 0 : v > 1 ? 1 : v
}

export function cruiseP() {
  return state.p
}

const clamp01 = (x) => (x < 0 ? 0 : x > 1 ? 1 : x)

/**
 * ความยาวที่ริบบิ้น "งอกออกไปแล้ว" (0..1 ของระยะที่เหลือทั้งหมด: ปลายเส้นหลัก + ช่วงต่อ)
 *
 * ไม่ได้เริ่มงอกทันทีที่เลื่อน — ช่วง cruStart แรกปล่อยให้กล้องถอยก่อน (ดู cruisePull)
 * เพราะปลายเส้นหลักจบต่ำกว่าขอบล่างของเฟรมอยู่แล้ว ถ้างอกทันทีปลายกับตัวละครจะไปโผล่
 * นอกจอสองสามวินาทีแรก
 */
export function cruiseGrow(t) {
  const at = Math.min(0.8, Math.max(0, t.cruStart))
  const x = clamp01((state.p - at) / (1 - at))
  /**
   * ออกตัวช้าแล้วค่อยเร่ง (x²) และไปได้ไกลสุดแค่ cruSpan ของทั้งเส้น
   *
   * จอแรกสูงวิวพอร์ตเดียว ระยะเลื่อนที่มีจึงสั้น ถ้าแมปตรง ๆ ทั้งเส้น ตัวละครจะพ้นเฟรม
   * ตั้งแต่เลื่อนไปได้ไม่ถึงหนึ่งในสาม — เหลือจอแรกที่ไม่มีตัวละครอยู่อีกสองในสาม
   * เร่งท้ายจึงพอดีกว่า: ช่วงต้นขยับนิดเดียว แล้วไหลออกตอนจอกำลังจะพ้นจริง ๆ
   */
  return clamp01(x * x * Math.max(0, t.cruSpan))
}

/**
 * พารัลแลกซ์ของจอแรก — 0..1 ตามระยะที่เลื่อน ใช้ขยับกล้อง (ดู CameraRig)
 *
 * เชิงเส้นตรง ไม่ผ่อน: พารัลแลกซ์ต้องเกาะนิ้วคนเลื่อนแบบหนึ่งต่อหนึ่ง ใส่ ease เข้าไป
 * แล้วภาพจะไหลต่อเองหลังหยุดเลื่อน อ่านเป็นของหลุดมือ ไม่ใช่ของที่ติดกับหน้า
 */
export function cruisePull(t) {
  return clamp01(state.p / Math.max(0.05, t.cruPull))
}

/**
 * ฉากยังต้องวาดอยู่ไหม — ชั้นฉากถูกตรึงเต็มจอ มันจึงไม่มีวัน "เลื่อนพ้น" ไปเอง
 *
 * เลื่อนไปไกลกว่าจอแรกสองเท่าตัว จอถัดไปทึบเต็มที่แล้ว ของข้างหลังไม่มีใครเห็น แต่ WebGL
 * ยังวาดทุกเฟรมอยู่ดีถ้าไม่สั่งหยุด — หยุด frameloop ตรงนั้น แล้วเปิดกลับเมื่อเลื่อนขึ้นมา
 */
let on = true
const subs = new Set()

export function setSceneOn(v) {
  if (v === on) return
  on = v
  subs.forEach((f) => f())
}

export function useSceneOn() {
  return useSyncExternalStore(
    (f) => {
      subs.add(f)
      return () => subs.delete(f)
    },
    () => on,
    () => true,
  )
}
