/**
 * ค่าทั้งก้อนเป็นวัตถุ *ที่ถูกแทน* ไม่ใช่วัตถุที่ถูกแก้ทับ
 *
 * useSyncExternalStore เทียบ snapshot ด้วย === ถ้า mutate วัตถุเดิมแล้วคืนตัวเดิม React
 * จะไม่เห็นว่ามีอะไรเปลี่ยน — แผงขยับแต่ฉากนิ่งสนิท (บทเรียนจาก whatidocard/stageTuner)
 */
let state = { ...DEFAULTS, ...load() }
const subs = new Set()

function load() {
  if (typeof localStorage === 'undefined') return null
  try {
    return JSON.parse(localStorage.getItem(KEY))
  } catch {
    return null
  }
}

function save() {
  try {
    localStorage.setItem(KEY, JSON.stringify(state))
  } catch {
    /* โหมดส่วนตัวของเบราว์เซอร์เขียนไม่ได้ — ค่าก็แค่ไม่ถูกจำ */
  }
}

/** เขียนค่าชุดหนึ่ง แล้วปลุกคนที่ดูอยู่ */
export function setStarTuner(patch) {
  let hit = false
  for (const k in patch) if (state[k] !== patch[k]) hit = true
  if (!hit) return
  state = { ...state, ...patch }
  save()
  for (const fn of subs) fn()
}

export function resetStarTuner() {
  setStarTuner(DEFAULTS)
}

function subscribe(fn) {
  subs.add(fn)
  return () => subs.delete(fn)
}

/** อ่านค่าทั้งก้อน — คืนวัตถุตัวเดิมจนกว่าจะมีการเขียน */
const snap = () => state

/**
 * อ่านค่าจากนอก React — สำหรับลูป rAF ที่เขียน DOM ตรง ๆ (ดู sections/aboutstar/AboutStar)
 *
 * ท่าเดียวกับ getTuner ของฉากแรก: ของที่อ่านทุกเฟรมต้องไม่ผูกกับการ re-render
 */
export const getStarTuner = () => state

export function useStarTuner() {
  return useSyncExternalStore(subscribe, snap, snap)
}

/** ประตูให้สคริปต์ตรวจงานด้วยภาพอ่าน/ตั้งค่าได้ — dev เท่านั้น */
if (import.meta.env.DEV && typeof window !== 'undefined') {
  window.__star = { get: () => state, set: setStarTuner, reset: resetStarTuner }
}
