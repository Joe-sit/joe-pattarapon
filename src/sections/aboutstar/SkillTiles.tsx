import { IconCode, IconPalette, IconSearch, type IconProps } from '@tabler/icons-react'
import { SKILLS } from '@/sections/whatido/WhatIDo'

/**
 * โมเสกแผ่นสกิล — ลายพิกเซลที่ไล่เป็นขั้นบันไดแล้วละลายเข้าหางานภาพด้านขวา
 *
 * ถอดจากการ์ดในภาพอ้างอิงที่เจ้าของงานส่งมา (การ์ด UNIVERSE'26): แถบภาพของการ์ดคือ
 * ตารางแผ่นจัตุรัสสีทึบ — เกือบดำ เทา ขาว ม่วง ฟ้า เหลือง ส้ม — บางแผ่นมีสัญลักษณ์
 * โมโนสเปซ ลายไล่เป็นบันไดจากมุมซ้ายล่างขึ้นไปทางขวาบน แล้วไปจบที่ขอบของรูป
 *
 * ### ทุกอย่างเป็น CSS ที่อ่าน `--in` ตัวเดียว
 *
 * จอนี้เขียน `--in` (0 = ยังอยู่ใต้จอ, 1 = เข้าที่) ทุกเฟรมที่เลื่อนอยู่แล้ว (ดู ./AboutStar)
 * โมเสกจึงไม่มีลูปวาดของตัวเอง ทุกแผ่นคิดท่าตัวเองจากค่านั้นด้วย `calc` — ความทึบ ขนาด
 * ระยะยก และส่วนที่กางออก
 *
 * ท่าโผล่ไล่กันทีละแผ่นด้วย `--d` (ลำดับตามแนวทแยง) มุมซ้ายล่างขึ้นก่อน ไล่ไปมุมขวาบน
 * ตาจึงอ่านเป็นคลื่นทางเดียว ไม่ใช่ทุกแผ่นเด้งพร้อมกัน
 *
 * ### "กางออก" คือแผ่นสกิลกินที่มากขึ้นจริง
 *
 * ขนาดแผ่นเป็น `calc()` ของหน่วยช่อง (`--cell`) คูณจำนวนช่องที่มันกิน แล้วบวกส่วนที่งอก
 * ตาม `--in` เฉพาะแผ่นสกิล พอเลื่อนจนสุดมันกว้างขึ้นราวหนึ่งช่องครึ่ง เบียดลายรอบ ๆ
 * — ขยายทั้งก้อนด้วย `transform` ได้ภาพคล้ายกันแต่สัดส่วนไม่เปลี่ยน อ่านเป็นการซูมเข้า
 * ไม่ใช่แผ่นที่โตขึ้น
 */

/** จำนวนช่องของตาราง — หน่วยของโมเสกคือความกว้างหนึ่งช่อง (`--cell`) */
const COLS = 6
const ROWS = 6

type Decor = {
  /** ช่องที่มุมซ้ายบนของแผ่น (นับจาก 0) */
  c: number
  r: number
  bg: string
  /** สัญลักษณ์ในแผ่น (ไม่มีก็เป็นแผ่นสีเปล่า) */
  ch?: string
  ink?: string
}

/**
 * ลายของชุด — สีตามต้นแบบแต่ **ไม่มีสีดำ** ตามที่เจ้าของงานสั่ง
 *
 * ต้นแบบวางแผ่นสีสดบนพื้นเกือบดำ ที่นี่พื้นเป็นสว่าง แผ่นเข้มสุดจึงเป็นม่วงอ่อน ไม่ใช่ดำ —
 * ความต่างที่ทำให้ลายอ่านเป็นบันไดมาจาก *วรรณะ* (ม่วง ฟ้า เขียว เหลือง ส้ม ชมพู) กับ
 * ความสว่างที่ไล่กันในโทนสว่าง ไม่ใช่การตัดกันระหว่างดำกับขาว
 *
 * ใช้เฉพาะสัญลักษณ์ที่ฟอนต์โมโนมีจริง: `⑂` (branch) ของภาพอ้างอิงตกเป็นตัวแทนของฟอนต์
 * สำรองแล้วอ่านเป็นตัวอื่นไปเลย (วัดมาแล้ว ได้รูปคล้าย Ψ) จึงใช้ `#` `>` `+` `/` `*` `(`
 *
 * ตำแหน่งไม่ได้สุ่ม: ทุกแผ่นแตะมุมกับเพื่อนอย่างน้อยหนึ่งมุม รูปรวมจึงเป็นบันไดเดียว และ
 * แถวบนขวาเบาลงเรื่อย ๆ เพื่อส่งสายตาไปหารูปที่อยู่ถัดไป
 */
const DECOR: Decor[] = [
  { c: 0, r: 5, bg: '#e9e4fb', ch: '+', ink: '#6b46e8' },
  { c: 1, r: 5, bg: '#ffffff' },
  { c: 2, r: 5, bg: '#f2eefc', ch: '(', ink: '#2b1d63' },
  { c: 4, r: 5, bg: '#d9cffa' },
  { c: 0, r: 4, bg: '#ffffff', ch: '/', ink: '#2b1d63' },
  { c: 1, r: 4, bg: '#cdf2dd' },
  { c: 3, r: 4, bg: '#6b8bf7' },
  { c: 4, r: 4, bg: '#f7c948', ch: '#', ink: '#4a3200' },
  { c: 1, r: 3, bg: '#a78bfa', ch: '*', ink: '#241154' },
  { c: 2, r: 3, bg: '#ffffff', ch: '>', ink: '#2b1d63' },
  { c: 4, r: 3, bg: '#f79a4d' },
  { c: 0, r: 2, bg: '#e6e1f7', ch: '+', ink: '#6b46e8' },
  { c: 2, r: 2, bg: '#ffb7d5', ch: '/', ink: '#5d1233' },
  { c: 3, r: 2, bg: '#ded6fb' },
  { c: 2, r: 1, bg: '#ffffff' },
  { c: 4, r: 1, bg: '#7c5cf0' },
  { c: 3, r: 0, bg: '#c4b2fb' },
  { c: 5, r: 2, bg: '#efeafd' },
  { c: 5, r: 4, bg: '#e9e4fb' },
]


/**
 * ไอคอนกับคู่สีของแต่ละหัวข้อ — **ข้อความมาจาก `SKILLS` ของ section เดิม ไม่เขียนใหม่**
 *
 * ที่นี่ถือแค่ "หน้าตา" ของแผ่น (ไอคอน สีพื้น สีตัวอักษร) ส่วนชื่อหัวข้อกับคำอธิบายอ่านจาก
 * sections/whatido/WhatIDo ซึ่งเป็นที่เดียวที่เก็บข้อความจริงของสกิล — ข้อความของ Research
 * ในนั้นยังเป็น Lorem ตามที่เจ้าของงานสั่งไว้ว่าจะเขียนเอง จอนี้ไม่แต่งแทน
 */
const LOOK: Record<string, { icon: React.ComponentType<IconProps>; bg: string; ink: string }> = {
  Research: { icon: IconSearch, bg: '#cdf2dd', ink: '#14663f' },
  Design: { icon: IconPalette, bg: '#f7c948', ink: '#4a3200' },
  Coding: { icon: IconCode, bg: '#a78bfa', ink: '#241154' },
}

/**
 * ลำดับการเล่าและ **ที่ยืนที่คละอยู่ในลาย** — ไม่ใช่เรียงเป็นคอลัมน์
 *
 * ต้นแบบวางแผ่นสีปนอยู่ในลายพิกเซล ไม่ได้แยกเป็นแถวของตัวเอง แผ่นสกิลจึงนั่งคนละที่กัน
 * ในตาราง แล้ว *กางทับลาย* ตอนถึงคิวของมัน — ลายเป็นฉากหลัง แผ่นที่กำลังเล่าเป็นของหน้า
 *
 * `gx`/`gy` คือทิศที่กางออก (+1 = ขวา/ลง, −1 = ซ้าย/ขึ้น) แผ่นที่อยู่ริมจึงกางเข้าหากลาง
 * ตารางเสมอ ไม่ล้นออกนอกกรอบ — ที่ยึดไว้คือมุมฝั่งตรงข้ามกับทิศที่กาง ไอคอนจึงไม่ขยับ
 *
 * จังหวะกาง/ค้าง/หุบของแต่ละแผ่นอยู่ที่ค่าคงที่ด้านล่าง (RISE · HOLD · FALL) แผ่นถัดไป
 * เริ่มกางพอดีตอนแผ่นก่อนหุบจบ คนดูจึงมีแผ่นที่ต้องอ่านทีละหนึ่งเสมอ
 */
const ORDER: { title: string; c: number; r: number; gx: 1 | -1; gy: 1 | -1 }[] = [
  { title: 'Research', c: 3, r: 5, gx: -1, gy: -1 },
  { title: 'Design', c: 1, r: 2, gx: 1, gy: 1 },
  { title: 'Coding', c: 4, r: 1, gx: -1, gy: 1 },
]
/**
 * จังหวะของการเล่า — **กาง ค้างให้อ่าน แล้วหุบ** ก่อนอันถัดไปกาง
 *
 * ค้างไว้ทั้งสามอันไม่ได้: มันทับกันเองและทับลาย แล้วคนดูก็ไม่รู้ว่าต้องอ่านอันไหนอยู่
 * ค่าที่แผ่นใช้จึงเป็น *เนิน* ไม่ใช่ขั้น — ขึ้นใน RISE ค้าง HOLD ลงใน FALL แล้วอันถัดไป
 * เริ่มขึ้นพอดีตอนอันนี้หุบจบ (STEP = RISE + HOLD + FALL)
 *
 * คิดบนระยะ `--tell` ของจอ (ยาวราวหนึ่งจอครึ่ง — ดู TELL_SPAN ใน ./AboutStar) ไม่ใช่
 * `--in` ที่จบภายในครึ่งจอ ไม่งั้นสามอันต้องเบียดกันจนอ่านไม่ทัน
 */
const FROM = 0.12
const RISE = 0.09
const HOLD = 0.13
const FALL = 0.08
const STEP = RISE + HOLD + FALL
/** กางออกจากหนึ่งช่องเป็นกี่ช่อง — กว้างพอใส่หัวข้อกับคำอธิบาย สูงพอให้ข้อความหายใจ */
const OPEN_W = 4
const OPEN_H = 2.7

/** ท่าโผล่ของแผ่นหนึ่ง — ลำดับ `--d` มาจากแนวทแยง (ซ้ายล่างก่อน) */
const appear = (c: number, r: number): React.CSSProperties => ({
  ['--d' as string]: (ROWS - 1 - r + c) / (COLS + ROWS),
  /**
   * ความทึบคูณตรง ๆ ได้ เบราว์เซอร์หนีบ 0..1 เองอยู่แล้ว — ส่วนขนาด/ระยะต้อง `clamp`
   * เพราะมันไม่มีขอบในตัว (สเกลติดลบคือพลิกแผ่น)
   */
  opacity: `calc((var(--in, 0) - var(--d)) * 3.4)`,
  transform: `translate3d(0, calc(clamp(0, (var(--d) + 0.16 - var(--in, 0)) * 3, 1) * 0.9 * var(--cell)), 0) scale(calc(0.84 + 0.16 * clamp(0, (var(--in, 0) - var(--d)) * 3.4, 1)))`,
})

/** ที่ยืนและขนาดของแผ่นลาย — หน่วยเป็นช่อง แปลงเป็นพิกเซลด้วย `--cell` */
const box = (c: number, r: number): React.CSSProperties => ({
  left: `calc(${c} * var(--cell))`,
  top: `calc(${r} * var(--cell))`,
  width: 'calc(var(--cell) - var(--gap))',
  height: 'calc(var(--cell) - var(--gap))',
})

/**
 * ความคืบหน้าของการกางแผ่นที่ i — 0..1 ในช่วงเวลาของมันเอง
 *
 * ใส่เป็นตัวแปร CSS แล้วให้ `calc` ในแผ่นใช้ต่อ ไม่ได้คำนวณเป็นตัวเลขใน JS: ค่า `--in`
 * เปลี่ยนทุกเฟรมที่เลื่อน ถ้าคิดใน JS ต้อง re-render ทุกเฟรมเพื่อเลขชุดเดิม
 */
const window_ = (i: number): React.CSSProperties => ({
  ['--s' as string]: FROM + i * STEP,
  /* เนิน: ขาขึ้นลบขาลง — ได้ 0 → 1 → 0 ด้วย calc ล้วน ไม่ต้องมีลูปใน JS */
  ['--o' as string]:
    `calc(clamp(0, (var(--tell, 0) - var(--s)) / ${RISE}, 1)` +
    ` - clamp(0, (var(--tell, 0) - var(--s) - ${(RISE + HOLD).toFixed(3)}) / ${FALL}, 1))`,
})

export function SkillTiles() {
  return (
    <div
      /**
       * โมเสก **ชิดขวา** — ขอบขวาของมันคือเส้นที่บรรจบกับงานภาพ
       *
       * ต้นแบบวางแผ่นให้ไปจบที่ขอบของรูป ไม่ใช่เริ่มจากขอบจอแล้วปล่อยให้เหลือช่องว่างกลาง
       * แถบ จึงยึดที่ `right` เท่ากับความกว้างของกรอบรูป (58% ของแถบ — ค่าเดียวกับกล่องที่
       * ครอบแคนวาสใน ./AboutStar) แล้วให้แผ่นไล่ออกไปทางซ้ายเอง
       *
       * หน่วยของโมเสกคือ `--cell` ผูกกับความสูงของแถบภาพ ไม่ใช่พิกเซลตายตัว — จอกว้างขึ้น
       * แผ่นไม่ล้นขอบล่างของแถบ
       */
      className="pointer-events-none absolute bottom-0 select-none"
      style={{
        /**
         * หนึ่งช่องเล็กสุดในสามทาง — **จอสูงไม่ได้แปลว่าแผ่นต้องใหญ่**
         *
         * เดิมผูกกับความสูงแถบภาพอย่างเดียว (band/6) บนจอสูง 1250px แถบกลายเป็น 720px
         * ช่องเลยโต 120px แผ่นสกิลที่กางออกกว้าง 550px ทับโมเสกทั้งกอง (เจ้าของงานเจอ
         * อาการนี้บนจอตัวเอง) — เพิ่มเพดานจากความกว้างจอและเพดานคงที่ ขนาดจึงโตได้เท่าที่
         * ผังรับได้จริง
         */
        ['--cell' as string]: 'min(var(--band) / 6, 7.2vw, 92px)',
        ['--gap' as string]: 'clamp(2px, 0.28vw, 4px)',
        /**
         * ขอบขวาของโมเสก = ขอบซ้ายของวงเล็บ (วัดจากฉาก ไม่ใช่กะเป็น %)
         *
         * `--tile-right` เขียนโดยลูปเลื่อนของจอจากกล่องจริงของรูป (ดู ./AboutStar)
         * ค่าสำรอง 58% ใช้แค่เฟรมแรกก่อนฉากรายงาน
         */
        right: 'var(--tile-right, 58%)',
        width: `calc(${COLS} * var(--cell))`,
        height: `calc(${ROWS} * var(--cell))`,
      }}
      aria-hidden
    >
      {DECOR.map((d) => (
        <div
          key={`${d.c}-${d.r}`}
          className="absolute grid place-items-center font-mono text-[calc(var(--cell)*0.4)] leading-none"
          style={{
            ...box(d.c, d.r),
            ...appear(d.c, d.r),
            background: d.bg,
            color: d.ink,
          }}
        >
          {d.ch}
        </div>
      ))}

      {/**
       * แผ่นสกิล — เริ่มเป็น *ไอคอนเปล่า* หนึ่งช่อง แล้วกางทีละแผ่นพร้อมข้อความ
       *
       * แผ่นยึดขอบขวาของโมเสก (`right: 0`) จึงกางออกไป *ทางซ้าย* ไอคอนเลยอยู่ที่เดิม
       * ตลอดทาง ไม่ใช่ถูกดันไปเรื่อย ๆ ตอนแผ่นยืด — ของที่โผล่มาใหม่คือข้อความ
       */}
      {ORDER.map((cell, i) => {
        const skill = SKILLS.find((s) => s.title === cell.title)
        const look = LOOK[cell.title]
        if (!skill || !look) return null
        const Icon = look.icon
        /**
         * กางทั้งกว้างและสูง โดยยึดมุมฝั่งตรงข้ามกับทิศที่กาง
         *
         * แผ่นที่กางไปทางซ้ายต้องเลื่อน `left` ถอยตามความกว้างที่งอกออกมา ไม่งั้นมันจะกาง
         * ไปทางขวาทับงานภาพ เช่นเดียวกับที่กางขึ้นต้องถอย `top` — ไอคอนจึงค้างอยู่ช่องเดิม
         * ตลอดทาง ของที่โผล่มาใหม่คือเนื้อเรื่อง
         */
        const dw = OPEN_W - 1
        const dh = OPEN_H - 1
        const left = cell.gx > 0 ? `calc(${cell.c} * var(--cell))` : `calc((${cell.c} - ${dw} * var(--o)) * var(--cell))`
        const top = cell.gy > 0 ? `calc(${cell.r} * var(--cell))` : `calc((${cell.r} - ${dh} * var(--o)) * var(--cell))`
        return (
          <div
            key={cell.title}
            className="absolute overflow-hidden"
            style={{
              ...window_(i),
              left,
              top,
              width: `calc((1 + ${dw} * var(--o)) * var(--cell) - var(--gap))`,
              height: `calc((1 + ${dh} * var(--o)) * var(--cell) - var(--gap))`,
              background: look.bg,
              color: look.ink,
              /* แผ่นที่กำลังเล่าอยู่หน้าลาย — ลายเป็นฉากหลัง ไม่ใช่ของที่ต้องแย่งที่กัน */
              zIndex: 2,
              opacity: `calc((var(--in, 0) - 0.08) * 6)`,
            }}
          >
            <div className="flex h-full items-start gap-[calc(var(--cell)*0.14)] p-[calc(var(--cell)*0.16)]">
              <Icon size="calc(var(--cell) * 0.46)" stroke={2.3} style={{ flex: 'none' }} />
              {/**
               * ข้อความจางเข้าหลังแผ่นกางไปแล้วครึ่งทาง — ตัวหนังสือที่โผล่พร้อมกับความกว้าง
               * จะถูกบีบอยู่ในช่องแคบ ๆ หนึ่งช่วงแล้วอ่านเป็นตัวอักษรที่ถูกตัด
               */}
              <div
                className="min-w-0 font-mono leading-tight"
                style={{ opacity: `calc((var(--o) - 0.18) * 2.4)` }}
              >
                <div className="text-[calc(var(--cell)*0.23)] font-semibold uppercase tracking-[0.1em]">
                  {skill.title}
                </div>
                <div className="mt-[0.4em] text-[calc(var(--cell)*0.15)] leading-snug opacity-80">
                  {skill.desc}
                </div>
              </div>
            </div>
          </div>
        )
      })}
    </div>
  )
}

export default SkillTiles
