export const portalScreenBox = { x: 0.5, y: 0.5, hw: 0, hh: 0, ready: false }

/**
 * หน่วยฉาก → สัดส่วนจอ แล้วเขียนลงกล่อง
 *
 * ฉากใช้กล้องออร์โธที่ zoom ผูกกับความสูงกรอบ (VIEW_H) ความสูงที่มองเห็นจึงเท่ากับ VIEW_H
 * หน่วยฉากพอดี และความกว้างเท่ากับ VIEW_H × อัตราส่วนจอ — แปลงได้ตรง ๆ ไม่ต้องฉายผ่าน
 * เมทริกซ์ (ท่าเดียวกับ screenRects ของจอเดิม ดู whatidocard/stageTuner)
 *
 * การเอียงบีบเงาบนจอด้านละ cos(มุม): กล้องออร์โธไม่มีเพอร์สเปกทีฟมาทำให้เบ้เพิ่ม หมุนรอบ
 * แกนตั้ง (yaw) บีบความกว้าง หมุนรอบแกนนอน (pitch) บีบความสูง ตรงตามนิยามของการฉายขนาน
 * — ส่วน roll ไม่ได้คิด: รูปที่ถูกหมุนต้องหมุนพิกัดสวนก่อนเข้าสูตร
 *
 * y ของจอนับลงจากขอบบน ส่วน y ของฉากนับขึ้น จึงกลับด้านหนึ่งครั้งตรงนี้ ที่เดียว
 */
export function portalScreen(t, scale, aspect, viewH = VIEW_H) {
  const w = viewH * aspect
  portalScreenBox.x = 0.5 + t.sX / w
  portalScreenBox.y = 0.5 - t.sY / viewH
  portalScreenBox.hw = (t.sRx * scale * Math.cos(t.sYaw * RAD)) / w
  portalScreenBox.hh = (t.sRy * scale * Math.cos(t.sPitch * RAD)) / viewH
  portalScreenBox.ready = true
  return portalScreenBox
}
