/**
 * เส้นรอบรูปที่ขนาดจริง — สเกลจากกล่อง −1..1 แล้ว **กลับด้านซ้าย-ขวา**
 *
 * ไฟล์ดีไซน์วาดวงเล็บปิด (`}`) คือแขนกางไปทางซ้าย ปลายแหลมชี้ขวา ผังของจอต้องการวงเล็บ
 * เปิด: ด้านแบนอยู่ซ้ายชิดกับโมเสก แขนกางไปทางขวาโอบงานภาพ ปลายแหลมชี้เข้าหาโมเสก
 * — เหมือนภาพอ้างอิง
 *
 * กลับที่นี่ทีเดียว ไม่ได้ไปหมุนกลุ่ม 180°: การหมุนรอบแกนตั้งพลิก *หน้า* ของก้อนไปด้วย
 * (วัสดุวาดเฉพาะด้านหน้า ด้านที่หันเข้ากล้องจะกลายเป็นด้านหลังแล้วหาย) และต้องกลับลำดับจุด
 * ด้วย เพราะการสะท้อนกลับทิศการวน (winding) ซึ่ง `ExtrudeGeometry` ใช้ตัดสินด้านในด้านนอก
 */
export function portalPoints(rx, ry) {
  const out = BRACKET.map(([x, y]) => new THREE.Vector2(-x * rx, y * ry))
  out.reverse()
  return out
}

/**
 * รูปเดียวกันในรูปของ CSS `clip-path: polygon(...)` — สำหรับวงเล็บที่เป็น DOM ไม่ใช่ของใน 3D
 *
 * จอ "สิ่งที่ทำ" มีวงเล็บสีส้มยืนอยู่ในคอลลาจ (โหนด 12822:290 ของไฟล์ดีไซน์) ซึ่งเป็น
 * *รูปเดียวกัน* กับพอร์ทัลของฉาก 3D — เอามาจากที่นี่ที่เดียว ไม่ก๊อปพาธไปไว้อีกไฟล์ ไม่งั้น
 * วันที่เปลี่ยนรูปวงเล็บจะมีของสองชิ้นที่หน้าตาไม่ตรงกัน
 *
 * แปลงสองอย่าง: กลับด้านซ้าย-ขวาให้ตรงกับ `portalPoints` (ไฟล์ดีไซน์วาดวงเล็บปิด ผังใช้
 * วงเล็บเปิด) และพลิกแกน y เพราะ CSS นับลง แต่กล่อง −1..1 ของรูปนี้นับขึ้น
 */
export function portalClipPath() {
  const pts = BRACKET.map(([x, y]) => {
    const cx = ((-x + 1) / 2) * 100
    const cy = ((1 - y) / 2) * 100
    return `${cx.toFixed(2)}% ${cy.toFixed(2)}%`
  })
  return `polygon(${pts.join(',')})`
}

/** รูปปิดของพอร์ทัล — ใช้ทำทั้งแผ่นแบนและช่อง stencil */
export function portalShape(rx, ry) {
  return new THREE.Shape(portalPoints(rx, ry))
}

/**
 * ตัวพอร์ทัลแบบหนา — ของ 3D จริง มีด้านข้าง
 *
 * `ExtrudeGeometry` จัดการรูปเว้าให้ในครั้งเดียว (ท่าเดียวกับกรอบหน้าต่างของ hero — ดู
 * roundedFrameGeo ใน newhero/stencilPortal) วงเล็บมีทั้งมุมเว้าและปลายแหลม การไล่จุด
 * แล้วต่อผนังเองจะพลาดที่มุมเว้าทุกครั้ง
 *
 * เลื่อนกลับมาครึ่งความลึก: extrude วิ่งจาก z = 0 ไป depth หน้าของรูปจึงอยู่ที่ z = +depth/2
 * พอดี ซึ่งเป็นระนาบที่หน้ากาก stencil ต้องไปนั่งทับ (ดู ./StarStage)
 */
export function portalExtrudeGeo(rx, ry, depth) {
  const g = new THREE.ExtrudeGeometry(portalShape(rx, ry), {
    depth,
    /**
     * **ไม่ลบมุม** — ขอบลบมุมทำให้หน้าของรูปเล็กกว่าเงาของมันเอง
     *
     * `ExtrudeGeometry` ที่เปิด bevel จะ *ยุบหน้า* เข้าไปเท่า bevelSize เงาที่กว้างสุดจึง
     * อยู่ที่กลางความหนา ไม่ใช่ที่หน้า — หน้ากาก stencil ซึ่งต้องทับ *หน้า* พอดีจะกว้างเกิน
     * ไปเท่า bevel แล้วตัวละครโผล่เลยขอบออกมาเป็นเส้นบาง ๆ รอบรูป (วัดมาแล้วตอนเป็นดาว)
     */
    bevelEnabled: false,
    curveSegments: 4,
  })
  g.translate(0, 0, -depth / 2)
  g.computeVertexNormals()
  return g
}

/**
 * เรขาคณิตแผ่นแบนรูปวงเล็บ
 *
 * `ShapeGeometry` สามเหลี่ยมหมดทั้งรูปในครั้งเดียว (รูปเว้า triangulate เองแล้วพลาดง่าย)
 * UV ของมันเป็น *พิกัดของรูป* ไม่ได้ไล่ 0..1 ตามกรอบ — ใครจะแปะลายต้องคิด uv เองจาก
 * ตำแหน่ง (ดูบันทึกเดียวกันที่ whatidocard/CardStage)
 */
export function portalGeo(rx, ry) {
  return new THREE.ShapeGeometry(portalShape(rx, ry))
}

/**
 * จุดนี้อยู่ในรูปไหม — นับรอยตัดของรัศมีกับเส้นรอบรูป (ray casting)
 *
 * รูปเว้าจึงใช้ "ระยะจากศูนย์" ตัดสินไม่ได้ และไม่มีนิพจน์ปิดอย่างที่ superellipse มี
 * วิธีนี้ถูกกับรูปหลายเหลี่ยมทุกแบบ รวมรูปที่มีปลายแหลมยื่นเข้ามากลางรูปอย่างวงเล็บ
 */
export function portalInside(x, y, rx, ry) {
  /* รูปถูกกลับด้านตอนสร้างจุด (ดู portalPoints) การทดสอบจึงต้องกลับพิกัดสวนก่อน */
  const nx = -x / rx
  const ny = y / ry
  let hit = false
  for (let i = 0, j = BRACKET.length - 1; i < BRACKET.length; j = i, i += 1) {
    const [xi, yi] = BRACKET[i]
    const [xj, yj] = BRACKET[j]
    if (yi > ny !== yj > ny && nx < ((xj - xi) * (ny - yi)) / (yj - yi) + xi) hit = !hit
  }
  return hit
}

