export type WhatIDoTuner = typeof DEFAULTS

/**
 * ค่าทั้งก้อนเป็นวัตถุ *ที่ถูกแทน* ไม่ใช่วัตถุที่ถูกแก้ทับ
 *
 * useSyncExternalStore เทียบ snapshot ด้วย === ถ้า mutate วัตถุเดิมแล้วคืนตัวเดิม React
 * จะไม่เห็นว่ามีอะไรเปลี่ยน — แผงขยับแต่จอนิ่งสนิท (บทเรียนจาก whatidocard/stageTuner)
 */
let state: WhatIDoTuner = { ...DEFAULTS, ...load() }
const subs = new Set<() => void>()

function load(): Partial<WhatIDoTuner> {
  if (typeof localStorage === 'undefined') return {}
  try {
    return JSON.parse(localStorage.getItem(KEY) ?? '{}') ?? {}
  } catch {
    return {}
  }
}

function save() {
  try {
    localStorage.setItem(KEY, JSON.stringify(state))
  } catch {
    /* โหมดส่วนตัวของเบราว์เซอร์เขียนไม่ได้ — ค่าก็แค่ไม่ถูกจำ */
  }
}

/** เขียนค่าชุดหนึ่ง แล้วปลุกคนที่ดูอยู่ */
export function setWhatIDoTuner(patch: Partial<WhatIDoTuner>) {
  let hit = false
  for (const k in patch) {
    if (state[k as keyof WhatIDoTuner] !== patch[k as keyof WhatIDoTuner]) hit = true
  }
  if (!hit) return
  state = { ...state, ...patch }
  save()
  for (const fn of subs) fn()
}

export function resetWhatIDoTuner() {
  setWhatIDoTuner(DEFAULTS)
}

function subscribe(fn: () => void) {
  subs.add(fn)
  return () => {
    subs.delete(fn)
  }
}

const snap = () => state

/** อ่านค่าจากนอก React — สำหรับลูป rAF และลูปวาดของฉาก 3D */
export const getWhatIDoTuner = () => state

export function useWhatIDoTuner() {
  return useSyncExternalStore(subscribe, snap, snap)
}

/** ประตูให้สคริปต์ตรวจงานด้วยภาพอ่าน/ตั้งค่าได้ — dev เท่านั้น */
if (import.meta.env.DEV && typeof window !== 'undefined') {
  ;(window as unknown as Record<string, unknown>).__wid = {
    get: () => state,
    set: setWhatIDoTuner,
    reset: resetWhatIDoTuner,
  }
}
