import { HAND_PARTS, type Part, placedParts, wavePose } from './handRig'

/**
 * ท่า "ทักทาย" ก่อนเข้าคอลลาจ — มือโบกที่ประกอบร่างใหม่เป็นวงเล็บส้ม
 *
 * มือคือกองสี่เหลี่ยมมนชิ้นละกระดูก (ดู ./handRig) ส่วนวงเล็บคือสี่เหลี่ยมสี่ชิ้นที่แทน
 * โครงของวงเล็บในไฟล์แบบ — การ morph จึงเป็น **ชิ้นต่อชิ้น**: ทุกชิ้นของมือวิ่งไปหาชิ้นของ
 * วงเล็บที่มันถูกจับคู่ไว้ พร้อมย่อ/ยืด/หมุน/เปลี่ยนรัศมีมุม
 *
 * ท่านี้เป็นไปได้เพราะทั้งสองฝั่ง *ประกอบจากทรงพื้นฐานชนิดเดียวกัน* ไม่ต้องมีพาธ ไม่ต้องสุ่ม
 * จุดให้เท่ากัน ไม่ต้องกลัวเส้นพับทับตัวเองระหว่างทาง (ปัญหาที่การผสมพาธต้องแก้ตลอด)
 *
 * ช่วง 12% สุดท้ายของท่า ชั้นนี้จางหายพร้อมกับที่ **วงเล็บจริงของคอลลาจ** (พาธของไฟล์แบบ
 * ดู `BRACKET_PATH` ใน ./WhatIDoScroll) โผล่เข้ามาแทน — สี่เหลี่ยมสี่ชิ้นเป็นแค่ตัวยืนแทน
 * ระหว่างทาง ตอนนิ่งผู้ชมจึงเห็นวงเล็บของจริงที่มีมุมมนกับคอคอดครบ
 */

/** กล่องที่มือยืนตอนทักทาย (พิกัดกรอบแบบ) — เยื้องขวาของกลางจอ ชิ้นส่วนจึงวิ่งไปขวาตอน morph */
export const HAND_BOX = { x: 520, y: 210, w: 400, h: 447 }

/**
 * โครงของวงเล็บเป็นสี่เหลี่ยมสามชิ้น — สัน แขนบน แขนล่าง
 *
 * เลขมาจากวงเล็บ *ที่ render ออกมาจริง* (นับพิกเซลจากภาพของแบบ): กรอบ x 876–1031
 * y 188–835 สันกว้าง 70 ชิดซ้าย (ขอบซ้ายนิ่งที่ 876 ทุกแถว) แขนสองอันยื่นออกขวาถึง 1031
 * สูง 84 ที่หัวและท้าย
 *
 * ของเดิมสร้างจากพิกัดที่ MCP คืนมา ซึ่งเป็นภาพกระจกและเยื้องซ้ายไป 69 — วงเล็บที่ morph
 * ไปจบจึงอยู่ผิดที่และกลับข้างกับวงเล็บพาธจริงที่ครอสเฟดเข้ามาแทน
 *
 * คอคอดกลางไม่ทำเป็นชิ้น: ในแบบมันแคบเหลือ ~13 (วัดที่ y 512 ได้ 876–888) เล็กเกินกว่าจะ
 * เป็นปลายทางของชิ้นไหน ปล่อยให้ตอนครอสเฟดไปพาธจริงเป็นคนพาคอคอดมาเอง
 */
const BRACKET_SLICES: Part[] = [
  { cx: 911, cy: 511.5, w: 70, h: 647, r: 8, rot: 0 },
  { cx: 988.5, cy: 230, w: 85, h: 84, r: 8, rot: 0 },
  { cx: 988.5, cy: 793, w: 85, h: 84, r: 14, rot: 0 },
]

/**
 * ชิ้นของมือชิ้นไหนไปเป็นชิ้นไหนของวงเล็บ (ดัชนีใน `BRACKET_SLICES`)
 *
 * เรียงตามลำดับของ `handParts`: ฝ่ามือ, นิ้ว 0–3 ชิ้นละสองท่อน, นิ้วโป้งสองท่อน
 * หลายชิ้นไปลงชิ้นเดียวกันได้ (ทับกันแล้วเป็นเงาเดียว) — จับคู่ให้ของที่อยู่ *ใกล้* ปลายทาง
 * อยู่แล้วไม่ต้องวิ่งไกล: ฝ่ามือกับนิ้วขวาสุดกลายเป็นสัน นิ้วบนกลายเป็นแขนบน นิ้วโป้งที่อยู่
 * ล่างซ้ายกลายเป็นแขนล่าง (สามปลายทาง ไม่มีคอคอด)
 */
const PART_TARGET = [0, 1, 1, 1, 1, 0, 0, 0, 0, 2, 2]

/** สีของสองทรงในไฟล์แบบ — ไล่สีระหว่าง morph ด้วย */
export const HAND_FILL = [78, 164, 242] as const
export const BRACKET_FILL = [241, 106, 26] as const

export type WaveArg = {
  /** องศาสูงสุดที่ข้อมือแกว่ง */
  waveAmp: number
  /** รอบต่อวินาที */
  waveFreq: number
  /** หน่วงเฟสไล่จากนิ้วซ้ายไปขวา */
  waveLag: number
  /** นิ้วแกว่งกี่ส่วนของข้อมือ */
  waveCurl: number
}

const REST_WAVE: WaveArg = { waveAmp: 0, waveFreq: 0, waveLag: 0, waveCurl: 0 }

const mix = (a: number, b: number, k: number) => a + (b - a) * k

/** ชิ้นส่วนพร้อมสีของเฟรมนั้น (ทุกชิ้นสีเดียวกัน — ที่ทับกันจึงเป็นเงาเดียว ไม่เห็นรอยต่อ) */
export type MorphPart = Part & { fill: string }

/**
 * ชิ้นที่ไปลงชิ้นไหนของวงเล็บ ออกเดินช้าเร็วต่างกัน (ดัชนีตาม `BRACKET_SLICES`)
 *
 * ไล่ตาม *ปลายทาง* ไม่ใช่ตามชิ้นของมือ: ถ้าไล่ทีละชิ้นของมือ (ปลายนิ้วก่อน ฝ่ามือหลัง)
 * มือจะ *แตก* — วัดจากภาพชุด m = 0…1 นิ้วโป้งหลุดออกไปเป็นก้อนเดี่ยวกลางจอ ส่วนฝ่ามือ
 * ยังเป็นกล่องฟ้านิ่งอยู่ที่เดิม ดูเหมือนของพัง ไม่ใช่ของที่กำลังพับตัว
 *
 * ไล่ตามปลายทางแทน: สันของวงเล็บก่อตัวก่อน แล้วแขนสองข้างค่อย *งอก* ออกมา
 * จากสันที่ลงล็อกแล้ว ก้อนจึงอยู่ติดกันตลอดทาง
 */
const TARGET_DELAY = [0, 0.12, 0.16]
/** ช่วงที่ใช้ทยอยปล่อย — ที่เหลือคือเวลาเดินของแต่ละชิ้น */
const STAGGER = 0.24

const clamp01 = (v: number) => (v < 0 ? 0 : v > 1 ? 1 : v)

/** เร่ง–หน่วงสองข้าง (smootherstep) ทุกชิ้นจึงออกตัวและลงจอดนุ่ม ไม่กระตุกหัวท้าย */
const ease = (t: number) => t * t * t * (t * (t * 6 - 15) + 10)

/**
 * ผสมสีใน *แสงเชิงเส้น* ไม่ใช่ใน sRGB ตรง ๆ
 *
 * ฟ้า→ส้มที่ผสมดิบ ๆ ผ่านเทาหมอง (วัดจากภาพชุดเดิม: กลางทางออกมาเป็นน้ำตาลโคลน)
 * ยกเป็นกำลัง 2.2 ก่อนผสมแล้วถอดกลับ กลางทางจึงสว่างและอิ่มกว่า
 */
const mixLight = (a: number, b: number, k: number) =>
  Math.round(255 * mix((a / 255) ** 2.2, (b / 255) ** 2.2, k) ** (1 / 2.2))

/**
 * ชิ้นส่วนทั้งชุดที่เวลา `t` และความคืบหน้า `m` (0 = มือ, 1 = วงเล็บ)
 *
 * แอมพลิจูดของการโบกถูกคูณด้วย (1 − m): ยิ่งกลายเป็นวงเล็บ การโบกยิ่งสงบลงจนนิ่งสนิท —
 * ถ้าไม่หัก วงเล็บส้มที่ลงล็อกแล้วจะสั่นอยู่ในผัง
 *
 * ทางเดินแยกสองแกน: **เข้าคอลัมน์ก่อน แล้วค่อยไหลขึ้น/ลง**
 *
 * เดิมไล่เป็นเส้นตรง (และเคยลองโก่งออกด้านข้าง) ทั้งสองแบบทำให้ชิ้นที่ปลายทางอยู่ไกล
 * — นิ้วโป้งที่ต้องไปเป็นแขนล่างที่ y 793 ขณะที่มือสูงแค่ y 657 — วิ่งทแยงข้ามที่ว่างไป
 * เป็นก้อนเดี่ยวตามหลังก้อนหลัก (เห็นจากภาพชุด m = 0…1) แกน x จึงเดินเสร็จก่อน: ทุกชิ้น
 * เข้าไปรวมเป็นสันเดียวก่อน แล้วแขนกับคอคอดค่อยรูดตามแกน y ออกมาจากสันนั้น ไม่มีชิ้นไหน
 * อยู่กลางที่ว่างเลย
 */
export function morphParts(m: number, t = 0, w: WaveArg = REST_WAVE): MorphPart[] {
  const pose = wavePose(t, w.waveAmp * (1 - m), w.waveFreq, w.waveLag, w.waveCurl)
  const hand = placedParts(pose, HAND_BOX)
  /**
   * สีเดียวทั้งก้อน ไล่ตาม `m` ไม่ใช่ตามความคืบหน้าของแต่ละชิ้น
   *
   * ไล่รายชิ้นแล้วสันเป็นส้มแต่แขนยังฟ้า (เห็นจากภาพชุด) มันอ่านเป็นของสองชิ้นมาต่อกัน
   * ไม่ใช่ของชิ้นเดียวที่เปลี่ยนรูป — เริ่มไล่ที่ 35% ตอนที่ยังพอเห็นเค้ามือ
   */
  const fill = morphFill(ease(clamp01((m - 0.35) / 0.45)))
  return hand.map((p, i) => {
    const q = BRACKET_SLICES[PART_TARGET[i] ?? 0]
    const start = TARGET_DELAY[PART_TARGET[i] ?? 0] ?? 0
    /* ค่าดิบ ไม่ผ่านเร่ง–หน่วง — สองแกนข้างล่างใส่เร่ง–หน่วงของตัวเองแยกกัน */
    const k = clamp01((m - start) / (1 - STAGGER))
    /**
     * สามจังหวะ: เลื่อนตามแกน x ก่อน → หุบ/ยืดขนาด → เลื่อนตามแกน y
     *
     * ขนาดต้องหุบ *ช้ากว่า* การเลื่อน ไม่ใช่พร้อมกัน: ฝ่ามือหุบจาก 293 เหลือ 85 ถ้าหุบเร็ว
     * ขอบซ้ายของมันหนีเข้าไปก่อนที่นิ้วโป้งจะตามเข้ามาทัน เกิดเป็นช่องว่างแล้วนิ้วโป้งลอย
     * เป็นก้อนเดี่ยวอยู่ข้างนอก (เห็นบนจอที่ 1.15vh) หุบช้าลงก้อนจึงเชื่อมกันตลอด
     */
    const kx = ease(clamp01(k / 0.55))
    const ks = ease(clamp01((k - 0.3) / 0.7))
    const ky = ease(clamp01((k - 0.35) / 0.65))
    return {
      cx: mix(p.cx, q.cx, kx),
      cy: mix(p.cy, q.cy, ky),
      w: mix(p.w, q.w, ks),
      h: mix(p.h, q.h, ks),
      r: mix(p.r, q.r, k),
      rot: mix(p.rot, q.rot, kx),
      fill,
    }
  })
}

/** สีที่ผสมแล้ว — 0 = ฟ้าของมือ, 1 = ส้มของวงเล็บ (ใช้เป็นสีตั้งต้นของ `<rect>`) */
export function morphFill(m: number) {
  const c = HAND_FILL.map((v, i) => mixLight(v, BRACKET_FILL[i], m))
  return `rgb(${c[0]}, ${c[1]}, ${c[2]})`
}

export { HAND_PARTS }
