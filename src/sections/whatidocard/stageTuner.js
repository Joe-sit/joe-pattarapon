/**
 * ค่าทั้งก้อนเป็นวัตถุ *ที่ถูกแทน* ไม่ใช่วัตถุที่ถูกแก้ทับ
 *
 * useSyncExternalStore เทียบ snapshot ด้วย === ถ้า mutate วัตถุเดิมแล้วคืนตัวเดิม React
 * จะไม่เห็นว่ามีอะไรเปลี่ยน — แผงขยับแต่ฉากนิ่งสนิท (วัดมาแล้ว: ลากสไลเดอร์แล้วฉากไม่ขยับ)
 * ทุกครั้งที่เขียนจึงต้องได้วัตถุใหม่ (ท่าเดียวกับ newhero/tuner)
 */
let state = { ...DEFAULTS, ...load() }
const subs = new Set()

function load() {
  if (typeof localStorage === 'undefined') return null
  try {
    return JSON.parse(localStorage.getItem(KEY))
  } catch {
    return null
  }
}

function save() {
  try {
    localStorage.setItem(KEY, JSON.stringify(state))
  } catch {
    /* โหมดส่วนตัวของเบราว์เซอร์เขียนไม่ได้ — ค่าก็แค่ไม่ถูกจำ ไม่ใช่เรื่องคอขาดบาดตาย */
  }
}

/** เขียนค่าชุดหนึ่ง แล้วปลุกคนที่ดูอยู่ */
export function setStageTuner(patch) {
  let hit = false
  for (const k in patch) if (state[k] !== patch[k]) hit = true
  if (!hit) return
  state = { ...state, ...patch }
  save()
  for (const fn of subs) fn()
}

/** ประตูให้สคริปต์ตรวจงานด้วยภาพอ่าน/ตั้งค่าได้ — dev เท่านั้น (ท่าเดียวกับ window.__tuner) */
if (import.meta.env.DEV && typeof window !== 'undefined') {
  window.__stage = { get: () => state, set: setStageTuner }
}

export function resetStageTuner() {
  setStageTuner(DEFAULTS)
}

function subscribe(fn) {
  subs.add(fn)
  return () => subs.delete(fn)
}

/**
 * กึ่งกลางของกองหน้าต่างทั้งสี่บาน (หน่วยโลก)
 *
 * ฉากเอาไปเลื่อนกองทั้งก้อนให้กลับมาอยู่กลางจอ: ผังเขียนด้วยตำแหน่งของแต่ละบาน ซึ่งพอลาก
 * จนพอใจแล้วกองมักเยื้องไปข้างใดข้างหนึ่ง การไปแก้ตำแหน่งทุกบานให้สมดุลเองคือการแก้ค่า
 * สี่ชุดเพื่อเรื่องเดียว — คิดกึ่งกลางจากกรอบรวมแล้วหักออกทีเดียวจบ
 *
 * ใบพอร์ทัลสูงกว่าใบอื่น (PORTAL_H) และกึ่งกลางเยื้องลง จึงคิดแยกจากใบที่เป็นแผ่นทึบ
 */
export function stackCenter(t) {
  let x0 = Infinity
  let x1 = -Infinity
  let y0 = Infinity
  let y1 = -Infinity
  for (const k of ['w1', 'w2', 'w3', 'w4']) {
    const s = t[`${k}s`]
    const h = (k === 'w1' ? PORTAL_H : CARD_H) * s
    const cy = t[`${k}y`] + (k === 'w1' ? PORTAL_DY * s : 0)
    x0 = Math.min(x0, t[`${k}x`] - (CARD_W * s) / 2)
    x1 = Math.max(x1, t[`${k}x`] + (CARD_W * s) / 2)
    y0 = Math.min(y0, cy - h / 2)
    y1 = Math.max(y1, cy + h / 2)
  }
  return { x: (x0 + x1) / 2, y: (y0 + y1) / 2 }
}

/**
 * กรอบของใบพอร์ทัลบนจอ — สัดส่วนของ *ความสูง* วิวพอร์ต
 *
 * จอก่อนหน้าเอาไปเป็นปลายทางของท่า genie (ดู sections/hero/ScrollTell) คิดที่นี่ที่เดียว
 * เพราะมันขึ้นกับค่าที่ลากได้จากแผง: ย้าย/ย่อใบพอร์ทัลแล้วกรอบต้องเปลี่ยนตามเอง ไม่ใช่ไป
 * วัดจากภาพแล้วพิมพ์ตัวเลขทับทุกครั้ง
 *
 * dx/dy = ระยะเยื้องจากกลางจอ (dy บวก = ต่ำกว่ากลาง เพราะแกน y ของจอชี้ลง)
 */
export function portalBox(t = state) {
  const c = stackCenter(t)
  const s = t.w1s
  const vh = (PORTAL_H * s) / VIEW_H
  return {
    vh,
    ar: CARD_W / PORTAL_H,
    dx: (t.w1x - c.x) / VIEW_H,
    dy: -(t.w1y + PORTAL_DY * s - c.y) / VIEW_H,
  }
}

/* ── ผังของกรอบหน้าจอ (ต้องตรงกับ CardStage) ─────────────────────────────── */
/** แถบหัวหน้าต่าง / ขอบรอบเนื้อ / มุมมน — ค่าเดียวกับที่ CardStage ใช้ปั้นเรขาคณิต */
const BAR_T = 0.95
const BAR = 0.14
const CARD_R = 0.34
const BODY_H = CARD_H - BAR_T
const HOLE_Y = -BAR_T / 2
const HOLE_W = CARD_W - BAR * 2 + 0.04
const HOLE_H = BODY_H + CARD_R - BAR * 2 + 0.04
const HOLE_CY = HOLE_Y - CARD_R / 2

/**
 * กรอบ "พื้นที่หน้าจอ" ของทุกบาน เป็นสัดส่วนของจอ (0..1 จากมุมซ้ายล่าง)
 *
 * ชั้นรอยสาด (ดู ./SplashReveal) เป็นแคนวาสของตัวเอง มันไม่รู้จัก stencil ของฉาก 3D จึงคัด
 * ด้วยกรอบพวกนี้แทน — รูปจริงจะโผล่ได้เฉพาะในจอของหน้าต่าง ไม่ไปทาทับกรอบดำหรือแถบหัว
 *
 * ใช้ได้เพราะทุกบานหันหน้าตรงเข้ากล้องและกล้องเป็นออร์โธ: กรอบบนจอจึงเป็นสี่เหลี่ยมตรง ๆ
 * ไม่ใช่รูปสี่เหลี่ยมที่ถูกเพอร์สเปกทีฟบิด (ถ้าวันหนึ่งเอียงบานกลับมา วิธีนี้ใช้ไม่ได้)
 */
export function screenRects(t = state, aspect = 16 / 9) {
  const c = stackCenter(t)
  const w = VIEW_H * aspect
  return ['w1', 'w2', 'w3', 'w4'].map((k) => {
    const s = t[`${k}s`]
    const portal = k === 'w1'
    const cy = (portal ? HOLE_CY : HOLE_Y) * s + t[`${k}y`] - c.y
    const cx = t[`${k}x`] - c.x
    const hw = ((portal ? HOLE_W : CARD_W - BAR * 2) * s) / 2
    const hh = ((portal ? HOLE_H : BODY_H - BAR) * s) / 2
    return { x: 0.5 + cx / w, y: 0.5 + cy / VIEW_H, hw: hw / w, hh: hh / VIEW_H }
  })
}

/** อ่านค่าทั้งก้อน — คืนวัตถุตัวเดิมจนกว่าจะมีการเขียน (ดูคำอธิบายที่ state) */
const snap = () => state

export function useStageTuner() {
  return useSyncExternalStore(subscribe, snap, snap)
}
