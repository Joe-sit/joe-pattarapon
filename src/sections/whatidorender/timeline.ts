/**
 * จังหวะของจอ "สิ่งที่ทำ" แบบเรนเดอร์ — ทุกช่วงเป็นสัดส่วนของระยะเลื่อนทั้ง section (0..1)
 *
 * รวมไว้ที่เดียว เพราะทั้งฉาก 3D (หน้าต่าง, ไทล์, วงแหวน, สีฉาก) และชั้น DOM (ข้อความสกิล)
 * อ่านช่วงเดียวกัน ถ้าต่างคนต่างเก็บตัวเลข วันหนึ่งข้อความจะเปลี่ยนก่อนสีฉากครึ่งจังหวะ
 */

/** ความยาว section เป็นจำนวนจอ — ระยะเลื่อนจริงคือ SCREENS − 1 จอ */
export const SCREENS = 9

export const TL = {
  /** หน้าต่างโผล่ทีละบานจนครบ */
  win: [0.03, 0.3] as const,
  /** ไทล์เรนเดอร์ทีละช่องจนเต็มจอ = รูปจริง */
  bucket: [0.31, 0.45] as const,
  /** วงแหวนสกิลคลี่เข้ามารอบตัว */
  ring: [0.45, 0.53] as const,
  /** หมุนวงแหวนทีละสกิล สีฉากเปลี่ยนตาม */
  skills: [0.53, 0.97] as const,
}

export const clamp01 = (v: number) => (v < 0 ? 0 : v > 1 ? 1 : v)

/** ความคืบหน้าภายในช่วง [a, b] */
export const span = (p: number, [a, b]: readonly [number, number]) => clamp01((p - a) / (b - a))

/**
 * ความคืบหน้าของสกิลแบบ "ค้างที่ละสกิล" — 0 = สกิลแรก, n−1 = สกิลสุดท้าย
 *
 * เลื่อนเชิงเส้นแล้ววงแหวนหมุนตลอด ไม่มีจังหวะให้อ่านชื่อที่มาอยู่หน้าสุดเลย ที่นี่แบ่งแต่ละ
 * ช่วงเป็น ค้าง → หมุน → ค้าง (เร่ง-หน่วงเฉพาะตอนหมุน) ชื่อจึงนิ่งให้อ่านได้ครึ่งหนึ่งของระยะ
 */
export function skillStep(p: number, n: number) {
  const raw = span(p, TL.skills) * (n - 1)
  const i = Math.min(n - 2, Math.floor(raw))
  const f = raw - i
  const k = clamp01((f - 0.3) / 0.4)
  return i + k * k * (3 - 2 * k)
}
