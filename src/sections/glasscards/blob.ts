/**
 * ทรงกลมเบี้ยว ๆ ที่ใช้ครอบรูป — คิดจากสมการ ไม่ใช่พาธที่ลากมือ
 *
 * ในแบบอ้างอิงรูปถูกครอบด้วยวงรีที่ *ไม่กลมจริง*: ด้านซ้ายบนเชิดขึ้น ด้านล่างแบนกว่า ขอบ
 * ทั้งวงไม่มีมุมเลย ถ้าใช้ `border-radius: 50%` จะได้วงรีเรขาคณิตเป๊ะซึ่งดูแข็งกว่าแบบ
 *
 * วิธีคิด: รัศมีแกว่งเป็นคลื่นรอบวงเหมือนทรงกลีบของจอ what-i-do แต่ตั้งความลึกไว้ต่ำมาก
 * (ราว 3–5%) และใช้คลื่นสองลูกซ้อน (n = 2 กับ n = 3) ผลคือขอบ *เอียงและป่องไม่เท่ากัน*
 * แต่ยังอ่านเป็นวงรี — ไม่ใช่ดอกไม้
 *
 * คืนค่าเป็นพาธในระบบ 0..1 (`objectBoundingBox`) จึงใช้เป็น `clipPath` ได้ทุกขนาดจอโดยไม่
 * ต้องคิดพิกเซล และไม่ต้องอัปเดตเมื่อกรอบรูปเปลี่ยนสัดส่วน
 */
export type BlobArg = {
  /** ความลึกของคลื่นลูกหลัก (สัดส่วนของรัศมี) */
  wob: number
  /** ความลึกของคลื่นลูกรอง — ลูกนี้ทำให้ขอบไม่สมมาตรซ้าย-ขวา */
  wob2: number
  /** หมุนคลื่นทั้งชุด (องศา) — เลื่อนว่าจะให้ด้านไหนป่อง */
  turn: number
}

export const BLOB: BlobArg = { wob: 0.062, wob2: 0.034, turn: -24 }

/**
 * จุดบนขอบทรง ในระบบ 0..1 (x ขวา, y ลง) — ต้นทางเดียวของทั้งพาธ SVG และรูปทรงในฉาก 3D
 *
 * คืนเป็นจุดไม่ใช่สตริง เพราะฝั่ง 3D ต้องเอาไปทำ `THREE.Shape` ถ้าเก็บเป็นพาธแล้วมาแกะ
 * สตริงทีหลัง ทรงสองฝั่งจะเริ่มเพี้ยนจากกันวันที่ใครแก้ตัวคูณผิดที่
 */
export function blobPoints({ wob, wob2, turn }: BlobArg, steps = 240) {
  const ph = (turn * Math.PI) / 180
  const out: [number, number][] = []
  for (let i = 0; i < steps; i += 1) {
    const th = (i / steps) * Math.PI * 2
    const r = 0.5 * (1 + wob * Math.cos(2 * (th + ph)) + wob2 * Math.cos(3 * (th - ph)))
    out.push([0.5 + r * Math.cos(th), 0.5 + r * Math.sin(th)])
  }
  return out
}

export function blobPath(arg: BlobArg, steps = 240) {
  return `${blobPoints(arg, steps)
    .map(([x, y], i) => `${i === 0 ? 'M' : 'L'}${x.toFixed(4)} ${y.toFixed(4)}`)
    .join('')}Z`
}
